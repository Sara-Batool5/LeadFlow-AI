-- LeadFlow AI Phase 2/3 schema. Safe to run more than once.
-- Phase 3 adds application behavior using the existing leads and workflow_events tables.
CREATE TABLE IF NOT EXISTS sales_owners (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(320) NOT NULL UNIQUE,
 specialization VARCHAR(160),
 is_available BOOLEAN NOT NULL DEFAULT TRUE,
 active_lead_limit INTEGER NOT NULL DEFAULT 20 CHECK (active_lead_limit > 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS leads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_reference VARCHAR(32) NOT NULL UNIQUE,
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(320) NOT NULL,
 company VARCHAR(200), job_title VARCHAR(160), website VARCHAR(500),
 company_size VARCHAR(80), industry VARCHAR(120), country VARCHAR(120),
 source VARCHAR(80) NOT NULL DEFAULT 'website_form', need_description TEXT NOT NULL,
 budget_range VARCHAR(100), timeline VARCHAR(100),
 status VARCHAR(40) NOT NULL DEFAULT 'new' CHECK (status IN ('new','qualifying','qualified','needs_review','assigned','contacted','closed_won','closed_lost')),
 priority VARCHAR(20) NOT NULL DEFAULT 'unassessed' CHECK (priority IN ('unassessed','low','medium','high','urgent')),
 assigned_owner_id BIGINT REFERENCES sales_owners(id) ON DELETE SET NULL,
 duplicate_of_lead_id BIGINT REFERENCES leads(id) ON DELETE SET NULL,
 consent_to_contact BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_leads_email_lower ON leads (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads (status);
CREATE INDEX IF NOT EXISTS idx_leads_created_at ON leads (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leads_assigned_owner ON leads (assigned_owner_id);
CREATE TABLE IF NOT EXISTS qualification_results (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id BIGINT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
 model_name VARCHAR(120), score INTEGER CHECK (score BETWEEN 0 AND 100),
 category VARCHAR(40) CHECK (category IN ('high_fit','medium_fit','low_fit','needs_review')),
 reasoning TEXT, missing_information JSONB NOT NULL DEFAULT '[]'::jsonb,
 recommended_next_action TEXT, human_review_required BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_qualification_lead ON qualification_results (lead_id, created_at DESC);
CREATE TABLE IF NOT EXISTS email_drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id BIGINT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
 recipient_email VARCHAR(320) NOT NULL, subject VARCHAR(300) NOT NULL, body TEXT NOT NULL,
 draft_status VARCHAR(30) NOT NULL DEFAULT 'pending_review' CHECK (draft_status IN ('pending_review','approved','rejected','sent')),
 approved_by VARCHAR(160), approved_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_email_drafts_lead ON email_drafts (lead_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_email_drafts_status ON email_drafts (draft_status);
CREATE TABLE IF NOT EXISTS workflow_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id BIGINT REFERENCES leads(id) ON DELETE SET NULL,
 event_type VARCHAR(100) NOT NULL, event_status VARCHAR(40) NOT NULL DEFAULT 'completed',
 message TEXT NOT NULL, details JSONB NOT NULL DEFAULT '{}'::jsonb,
 actor VARCHAR(160) NOT NULL DEFAULT 'system', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_workflow_events_lead ON workflow_events (lead_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_workflow_events_created_at ON workflow_events (created_at DESC);